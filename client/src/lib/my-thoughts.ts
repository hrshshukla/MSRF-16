const templatesByLanguage = {
  en: hindiThoughtTemplates,
  hi: hindiThoughtTemplates,
  mr: marathiThoughtTemplates,
} as const;

export function getDefaultThought(language: Language, templateId: number): string {
  const templates = templatesByLanguage[language] ?? templatesByLanguage.en;
  const safeId = Number.isInteger(templateId) ? Math.abs(templateId) : 0;
  return templates[safeId % templates.length];
}

export function resolveMyThoughts(
  customThought: string | null | undefined,
  language: Language,
  templateId: number | null | undefined,
): string {
  if (customThought?.trim()) return customThought;
  return getDefaultThought(language, templateId ?? 0);
}